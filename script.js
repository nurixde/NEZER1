function switchTab(tab) {
    document.querySelectorAll('.tab-btn').forEach(btn => {
        btn.className = "tab-btn px-8 py-3 font-medium uppercase tracking-wider text-sm rounded bg-white text-gray-700 shadow-sm hover:bg-gray-100 transition-all";
    });
    
    const targetTab = document.getElementById(`tab-${tab}`);
    if (targetTab) {
        targetTab.className = "tab-btn px-8 py-3 font-medium uppercase tracking-wider text-sm rounded bg-brandRed text-white shadow-md transition-all";
    }
    
    renderCatalog(tab);
}

function toggleCard(id) {
    const card = document.getElementById(`card-${id}`);
    if (card) {
        card.classList.toggle('rotate-y-180');
    }
}

// Modals
function openModal(id) {
    const modal = document.getElementById(id);
    if (modal) {
        modal.classList.remove('hidden');
        document.body.style.overflow = 'hidden';
    }
}

function closeModal(id) {
    const modal = document.getElementById(id);
    if (modal) {
        modal.classList.add('hidden');
        document.body.style.overflow = 'auto';
    }
}

function openBuyModal(productName) {
    const modalTitle = document.getElementById('buyModalTitle');
    if (modalTitle) {
        modalTitle.textContent = `Ваш заказ: ${productName}`;
    }
    openModal('buyModal');
}

function handleModalSubmit(event, modalId) {
    event.preventDefault();
    closeModal(modalId);
    setTimeout(() => {
        openModal('successModal');
        event.target.reset();
    }, 300);
}

function handleFormSubmit(event) {
    event.preventDefault();
    openModal('successModal');
    event.target.reset();
}

// Слайдер (3 фото)
let currentSlide = 0;
const slidesCount = 3;

function updateCarousel() {
    const track = document.getElementById('carouselTrack');
    if (track) {
        track.style.transform = `translateX(-${currentSlide * 100}%)`;
    }
}

function nextSlide() {
    currentSlide = (currentSlide + 1) % slidesCount;
    updateCarousel();
}

function prevSlide() {
    currentSlide = (currentSlide - 1 + slidesCount) % slidesCount;
    updateCarousel();
}

// Кнопка прокрутки Наверх (Снизу справа)
window.addEventListener('scroll', () => {
    const scrollBtn = document.getElementById('scrollTopBtn');
    if (window.scrollY > 400) {
        scrollBtn.classList.remove('opacity-0', 'pointer-events-none');
        scrollBtn.classList.add('opacity-100');
    } else {
        scrollBtn.classList.add('opacity-0', 'pointer-events-none');
        scrollBtn.classList.remove('opacity-100');
    }
});

function scrollToTop() {
    window.scrollTo({
        top: 0,
        behavior: 'smooth'
    });
}

