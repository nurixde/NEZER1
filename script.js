function toggleLangDropdown() {
    const langMenu = document.getElementById('langMenu');
    langMenu.classList.toggle('hidden');
}

// Закрыть меню при клике вне его
document.addEventListener('click', (e) => {
    const btn = document.getElementById('langDropdownBtn');
    const menu = document.getElementById('langMenu');
    if (btn && menu && !btn.contains(e.target) && !menu.contains(e.target)) {
        menu.classList.add('hidden');
    }
});

// Выбор языка
function selectLanguage(lang) {
    currentLang = lang;
    
    // Обновить плашку в кнопке
    document.getElementById('currentFlag').className = `fi ${langFlags[lang].flag} text-base`;
    document.getElementById('currentLangLabel').textContent = langFlags[lang].label;
    
    // Скрыть меню
    document.getElementById('langMenu').classList.add('hidden');

    // Перевести статичные тексты
    document.querySelectorAll('[data-lang]').forEach(element => {
        const key = element.getAttribute('data-lang');
        if (translations[lang][key]) {
            element.innerHTML = translations[lang][key];
        }
    });

    // Перерисовать каталог с переведенными кнопками
    renderCatalog(currentTab);
}

